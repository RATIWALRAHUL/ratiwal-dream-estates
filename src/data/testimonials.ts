// Helper Functions
export function getAllPublishedTestimonials(): Testimonial[] {
  return testimonials.filter((t) => t.clientConsent);
}

export function getFeaturedTestimonials(): Testimonial[] {
  return testimonials.filter((t) => t.clientConsent && t.featured);
}

export function getAllPublishedCaseStudies(): CaseStudy[] {
  return caseStudies.filter((cs) => cs.published && cs.clientConsent);
}

export function getCaseStudyBySlug(slug: string): CaseStudy | undefined {
  return caseStudies.find(
    (cs) => cs.slug.toLowerCase() === slug.toLowerCase() && cs.published && cs.clientConsent
  );
}

export function getCaseStudiesForLocation(locationSlug: string): CaseStudy[] {
  return caseStudies.filter(
    (cs) => cs.relatedLocationSlug?.toLowerCase() === locationSlug.toLowerCase() && cs.published && cs.clientConsent
  );
}
