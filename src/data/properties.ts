export function getFeaturedProperties(): Property[] {
  return properties.filter((p) => p.featured);
}

export function getPropertyBySlug(slug: string): Property | undefined {
  return properties.find((p) => p.slug.toLowerCase() === slug.toLowerCase());
}

export function getRelatedProperties(currentSlug: string, count: number = 3): Property[] {
  const current = getPropertyBySlug(currentSlug);
  if (!current) return [];

  const others = properties.filter((p) => p.slug.toLowerCase() !== currentSlug.toLowerCase());

  // Prioritize same city, then same propertyType
  const sameCity = others.filter((p) => p.city.toLowerCase() === current.city.toLowerCase());
  const sameType = others.filter((p) => p.propertyType === current.propertyType && !sameCity.includes(p));

  return [...sameCity, ...sameType, ...others].slice(0, count);
}
